def _run(code):
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        exec(code, {})
    return buf.getvalue().rstrip()


def _prepare(check):
    parts = []
    n = 0
    for part in check["parts"]:
        qs = []
        for q in part["questions"]:
            n += 1
            q = dict(q, id="%s-%d" % (check["id"], n), num=n, skippable=part["skippable"])
            if q["kind"] == "output":
                q["answer"] = _run(q["code"])
            elif q["kind"] == "choice":
                right = q["options"][0]
                opts = list(q["options"])
                random.Random(q["id"]).shuffle(opts)
                q["options"] = opts
                q["answer"] = right
            # числовой ответ — на телефоне вместо системной клавиатуры показываем свою цифровую
            q["numeric"] = q["kind"] != "choice" and bool(re.fullmatch(r"-?\d+([.,]\d+)?", str(q["answer"]).strip()))
            qs.append(q)
        parts.append(dict(part, questions=qs))
    return dict(check, parts=parts, questions=[q for p in parts for q in p["questions"]],
                topics=list(dict.fromkeys(q["topic"] for p in parts for q in p["questions"])))


