def out(topic, code, why="", text="Что выведет этот код?"):
    return {"kind": "output", "topic": topic, "text": text, "code": code, "why": why}


def ans(topic, text, answer, why="", code=""):
    return {"kind": "answer", "topic": topic, "text": text, "code": code, "answer": str(answer), "why": why}


def choice(topic, text, options, why="", code=""):
    return {"kind": "choice", "topic": topic, "text": text, "code": code, "options": options, "why": why}


