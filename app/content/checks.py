def _same(given, right):
    given, right = normalize_answer(given).lower(), normalize_answer(right).lower()
    if re.fullmatch(r"-?\d+([.,]\d+)?", given):  # с экранной клавиатуры дробь приходит через запятую
        given, right = given.replace(",", "."), right.replace(",", ".")
        if re.fullmatch(r"-?\d+(\.\d+)?", right):   # «10,0» и «10» — одно число
            return abs(float(given) - float(right)) < 1e-9
    return given == right


def grade(check, answers):
    """answers: {id вопроса: ответ или SKIP}. Возвращает разбор по вопросам и по темам."""
    items, topics = [], {t: {"topic": t, "right": 0, "total": 0, "skipped": 0} for t in check["topics"]}
    for q in check["questions"]:
        given = answers.get(q["id"], "")
        skipped = given == SKIP
        ok = not skipped and given.strip() != "" and _same(given, q["answer"])
        items.append({"q": q, "given": "" if skipped else given, "ok": ok, "skipped": skipped})
        t = topics[q["topic"]]
        t["total"] += 1
        t["right"] += ok
        t["skipped"] += skipped
    right = sum(i["ok"] for i in items)
    skipped = sum(i["skipped"] for i in items)
    return {"items": items, "topics": list(topics.values()), "right": right, "total": len(items), "skipped": skipped}
