def _norm(s):
    return re.sub(r"\s+", "", str(s)).replace(",", ".").lower()


def grade_answer(task, given):
    """Сколько первичных баллов за ответ (как на экзамене). Для «long» не вызывается."""
    full = EXAMS[task["exam"]]["numbers"][task["num"]][1]
    g, right = _norm(given), _norm(task["answer"])
    if not g:
        return 0
    if task["mode"] == "num":
        # «60 %», «2,69 л», «12 г/моль» — число с единицей измерения тоже засчитываем
        m = re.fullmatch(r"(-?\d+(?:\.\d+)?)(?:%|[a-zа-яё°/³²()]+\.?)?", g)
        try:
            return full if m and abs(float(m.group(1)) - float(right)) < 1e-6 else 0
        except ValueError:
            return 0
    if right.isdigit():                   # цифры можно разделять запятыми, точками, дефисами, слешами
        g = re.sub(r"[.;\-/–—]", "", g)
    if task["mode"] == "set":
        return full if len(g) == len(right) and sorted(g) == sorted(right) else 0
    if g == right:
        return full
    if full == 2 and len(g) == len(right) and sum(a != b for a, b in zip(g, right)) == 1:
        return 1
    return 0


