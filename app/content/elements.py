def _clean_credit(text):
    """Подпись автора фото без служебных хвостов Викисклада: «( talk )», адрес сайта, имя исходного файла."""
    t = _re.sub(r"^\S+\.(?:jpe?g|png)\s*:\s*", "", text)
    t = _re.sub(r"\(\s*talk\s*\)|\(\s*(?:www\.)?pse-mendelejew\.de\s*\)\.?|(?:www\.)?pse-mendelejew\.de", "", t)
    t = _re.sub(r"Contact email:.*$", "", t)
    t = _re.sub(r"^(\S+) = \1", r"\1", t.strip())
    t = t.replace("“", "").replace("\"", "")
    t = _re.sub(r"\(\s+", "(", t)
    t = _re.sub(r"\s+([,.)])", r"\1", _re.sub(r"\s{2,}", " ", t)).strip(" .")
    if t.count("(") > t.count(")"):
        t += ")"
    return t


