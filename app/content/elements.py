def _filling(z):
    left, occ = z, {}
    for orb in _ORDER:
        if left <= 0:
            break
        occ[orb] = min(_CAP[orb[-1]], left)
        left -= occ[orb]
    occ.update(_EXCEPT.get(z, {}))
    return occ


def electron_config(z):
    """Краткая электронная конфигурация с ядром благородного газа: Cl → [Ne] 3s² 3p⁵. Для z > 56 — None."""
    if z > 56:
        return None
    occ = _filling(z)
    core_z, core = next(((nz, s) for nz, s in _NOBLE if nz < z), (0, ""))
    core_occ = _filling(core_z) if core_z else {}
    parts = []
    for orb in sorted(occ, key=lambda o: (int(o[0]), "spdf".index(o[1]))):
        n = occ[orb] - core_occ.get(orb, 0)
        if n > 0:
            parts.append(orb + str(n).translate(_SUPERS))
    return ("[%s] " % core if core else "") + " ".join(parts)


