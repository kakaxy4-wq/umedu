"""Короткие вопросы с выбором ответа для номеров, где раньше была самопроверка.

Факты — школьные и однозначные: даты, авторство, устройство клетки, нормы языка.
Варианты перемешиваются, в ответ пишется номер.
"""


def ask(r, prompt, correct, wrongs):
    opts = []
    for item in (correct, *wrongs):
        if item not in opts:
            opts.append(item)
    if len(opts) < 4:
        raise ValueError(prompt)
    r.shuffle(opts)
    n = opts.index(correct) + 1
    lines = "\n".join("%d) %s" % (i + 1, s) for i, s in enumerate(opts))
    return {"text": prompt.strip() + "\n\n" + lines + "\n\nВ ответе запиши номер верного варианта.",
            "answer": str(n),
            "explain": "Верный вариант — %d: %s." % (n, correct),
            "steps": ["Прочитай все варианты.", "Оставь тот, который совпадает с правилом или фактом.",
                      "Это вариант %d." % n],
            "data": {"kind": "choice", "options": opts, "right": correct}}


def _pool(items):
    def gen(r, items=items):
        prompt, correct, wrongs = r.choice(items)
        return ask(r, prompt, correct, wrongs)
    return gen


