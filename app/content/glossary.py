"""Расшифровка сокращений и терминов.

На всём сайте фильтр `md` оборачивает их в <abbr title="…"> (подсказка при наведении),
а на странице подготовки к уроку внизу собирается «Словарик» из встретившихся терминов.
"""
import re

GLOSSARY = [
    ("ЭВМ", "электронная вычислительная машина — так в СССР называли компьютеры"),
    ("МЭСМ", "Малая электронная счётная машина — первая советская ЭВМ (1951)"),
    ("БЭСМ", "Большая электронная счётная машина — следующая ЭВМ С. А. Лебедева"),
    ("ENIAC", "Electronic Numerical Integrator and Computer — «электронный числовой интегратор и вычислитель», США, 1945"),
    ("МГУ", "Московский государственный университет имени М. В. Ломоносова"),
    ("ИИ", "искусственный интеллект — программы, которые учатся на примерах, а не следуют готовым правилам"),
    ("NASA", "Национальное управление по аэронавтике и исследованию космического пространства (США)"),
    ("TIOBE", "нидерландская компания TIOBE Software; каждый месяц публикует рейтинг популярности языков программирования"),
    ("ДЗ", "домашнее задание"),
    ("API", "Application Programming Interface — программный интерфейс: правила, по которым одна программа обращается к другой"),
    ("JSON", "JavaScript Object Notation — текстовый формат для обмена данными: списки и словари в виде текста"),
    ("FPS", "frames per second — кадров в секунду"),
    ("VS Code", "Visual Studio Code — бесплатный редактор кода"),
    ("ASCII", "American Standard Code for Information Interchange — старая таблица кодов латинских букв, цифр и знаков"),
    ("WASD", "клавиши W, A, S, D — движение вверх, влево, вниз, вправо в играх"),
    ("MVP", "minimum viable product — самая простая версия программы, которая уже работает"),
    ("ОГЭ", "основной государственный экзамен в 9 классе"),
    ("КБ", "килобайт — около тысячи байт; один байт хранит одну латинскую букву"),
    ("int", "integer — целое число"),
    ("float", "floating point — дробное число («с плавающей точкой»)"),
    ("str", "string — строка, текст"),
    ("hp", "health points — очки здоровья"),
    ("dmg", "damage — урон"),
]

_PATTERNS = [(term, expl, re.compile(r"(?<![\w.])%s(?!\w)" % re.escape(term))) for term, expl in GLOSSARY]
# код, рисунки и теги не трогаем: <abbr> внутри <svg> сломал бы надпись
_CODE = re.compile(r"(<svg.*?</svg>|<pre.*?</pre>|<code[^>]*>.*?</code>|<abbr.*?</abbr>|<[^>]+>)", re.S)


def add_abbr(html):
    """Оборачивает сокращения в <abbr>, не трогая код и теги. Каждое — только при первом упоминании."""
    seen = set()
    parts = _CODE.split(html)
    for i, part in enumerate(parts):
        if i % 2:  # код или тег
            continue
        for term, expl, rx in _PATTERNS:
            if term in seen or term[0].islower():  # имена типов (int, str…) в тексте не размечаем — они почти всегда в коде
                continue
            new, n = rx.subn(lambda m: '<abbr title="%s">%s</abbr>' % (expl, m.group(0)), part, count=1)
            if n:
                seen.add(term)
                part = new
        parts[i] = part
    return "".join(parts)


def terms_in(text):
    """Термины словаря, которые встречаются в тексте (для «Словарика» на странице подготовки)."""
    plain = re.sub(r"<[^>]+>", " ", text)
    return [(t, e) for t, e, rx in _PATTERNS if rx.search(plain)]
