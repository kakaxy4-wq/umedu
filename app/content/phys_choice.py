def _process(r, which):
    """which 12 или 13: два параметра процесса и как они меняются."""
    g = r.choice(["isobar", "isochor", "heat_ice"])
    extra = r.randint(2, 90)
    if g == "isobar":
        story = ("Идеальный газ нагрели на %d °C в цилиндре под подвижным поршнем. Давление газа не меняется." % extra)
        pairs = [("объём газа", "увеличивается"), ("давление газа", "не изменяется")]
    elif g == "isochor":
        story = ("Идеальный газ нагрели на %d °C в закрытом жёстком баллоне. Объём газа не меняется." % extra)
        pairs = [("давление газа", "увеличивается"), ("объём газа", "не изменяется")]
    else:
        story = ("Лёд массой %d г при 0 °C тает в открытом сосуде. Температура смеси остаётся 0 °C, пока есть лёд."
                 % (extra * 10))
        pairs = [("внутренняя энергия", "увеличивается"), ("температура", "не изменяется")]
    if which == 13:
        pairs = list(reversed(pairs))
    ans = "".join(CHANGES[c] for _, c in pairs)
    legend = "1 — увеличивается, 2 — уменьшается, 3 — не изменяется"
    text = ("%s Как меняются величины?\n\n%s\n\n%s.\nВ ответе две цифры подряд: сначала про первую величину, потом про вторую."
            % (story, "\n".join("%d) %s" % (i + 1, name) for i, (name, _) in enumerate(pairs)), legend))
    steps = ["Запиши, что в процессе удерживают постоянным.",
             "Вторая величина меняется так, как велит уравнение состояния или переход энергии.",
             "Ответ %s: %s." % (ans, ", ".join("%s — %s" % p for p in pairs))]
    return _out(text, ans, "%s Ответ %s." % (story, ans), steps,
                {"kind": "process", "group": g, "names": [n for n, _ in pairs], "changes": [c for _, c in pairs]})


