def _digits(pairs, shown, key):
    """Номер столбца shown для каждого ключа key(pair), цифры подряд."""
    return "".join(str(shown.index(key(p)) + 1) for p in pairs)


def p1(r):
    rows = r.sample(UNITS, 3)
    shown = [u for _, u in rows]
    r.shuffle(shown)
    ans = _digits(rows, shown, lambda p: p[1])
    lines = "\n".join("%s) %s" % (i + 1, u) for i, u in enumerate(shown))
    quants = ", ".join(q for q, _ in rows)
    text = ("Установи соответствие между физической величиной и единицей СИ. "
            "Величины по порядку: %s.\n\nЕдиницы:\n%s\n\nВ ответе запиши три цифры подряд: номер единицы для каждой "
            "величины в том же порядке." % (quants, lines))
    steps = ["Вспомни, чем измеряют каждую величину в СИ, без приставок.",
             "Порядок цифр — как перечислены величины, не как удобнее читать.",
             "Получается %s: %s." % (ans, ", ".join("%s — %s" % p for p in rows))]
    return _out(text, ans, "Верно: %s." % ", ".join("%s — %s" % p for p in rows), steps,
                {"kind": "units", "quants": [q for q, _ in rows], "shown": shown})


def p2(r):
    right = r.choice(DEVICES)
    opts = [right[1]]
    while len(opts) < 4:
        name = r.choice(DEVICES)[1]
        if name not in opts:
            opts.append(name)
    r.shuffle(opts)
    ans = opts.index(right[1]) + 1
    text = ("Каким прибором измеряют %s?\n\n%s\n\nВ ответе запиши номер варианта."
            % (right[0], "\n".join("%d) %s" % (i + 1, o) for i, o in enumerate(opts))))
    steps = ["Прибор называют по величине, которую он измеряет.",
             "Лишние варианты измеряют другие величины.",
             "Нужен %s — это вариант %d." % (right[1], ans)]
    return _out(text, ans, "%s измеряют %s, вариант %d." % (right[0].capitalize(), right[1], ans), steps,
                {"kind": "device", "what": right[0], "options": opts})


def p3(r):
    situation, name = r.choice(PHENOMENA)
    shown = situation[:-1] + " (опыт №%d)." % r.randint(2, 50)
    names = [name]
    while len(names) < 4:
        other = r.choice(PHENOMENA)[1]
        if other not in names:
            names.append(other)
    r.shuffle(names)
    ans = names.index(name) + 1
    text = ("%s Какое явление здесь главное?\n\n%s\n\nВ ответе запиши номер варианта."
            % (shown, "\n".join("%d) %s" % (i + 1, n) for i, n in enumerate(names))))
    steps = ["Отдели явление от прибора и от вещества.",
             "Посмотри, меняется ли состояние, направление луча или заряд.",
             "Это %s, вариант %d." % (name, ans)]
    return _out(text, ans, "Описано %s — вариант %d." % (name, ans), steps,
                {"kind": "phenomenon", "situation": situation, "options": names})


def p4(r):
    m, h = r.randint(2, 9), r.randint(2, 8)
    pe = m * 10 * h
    # тело подняли равномерно: PE выросла, KE не изменилась
    s1 = "Потенциальная энергия тела увеличилась на %d Дж." % pe
    s2 = "Кинетическая энергия тела при подъёме не изменилась."
    true = [s1, s2]
    false = ["Потенциальная энергия тела уменьшилась на %d Дж." % pe,
             "Кинетическая энергия тела выросла на %d Дж." % pe]
    pick = [r.choice(true), r.choice(false)]
    r.shuffle(pick)
    nums = [str(i + 1) for i, s in enumerate(pick) if s in true]
    ans = "".join(nums)
    text = ("Тело массой %d кг медленно и равномерно подняли на %d м. g = 10 м/с². Какие утверждения верны?\n\n%s\n\n"
            "В ответе запиши номера верных утверждений подряд, в порядке возрастания."
            % (m, h, "\n".join("%d) %s" % (i + 1, s) for i, s in enumerate(pick))))
    steps = ["При равномерном подъёме скорость не меняется, значит кинетическая энергия та же.",
             "Потенциальная энергия растёт на mgh = %d · 10 · %d." % (m, h),
             "Верные номера: %s." % ans]
    return _out(text, ans, "mgh = %d Дж. Верны утверждения %s." % (pe, ans), steps,
                {"kind": "lift", "m": m, "h": h, "statements": pick})


