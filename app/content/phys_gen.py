"""Свои варианты по физике для umedu 2.0: расчётные номера ОГЭ (6–11) и ЕГЭ (1–4, 7, 8, 11–13, 16).

Устроено как app/content/math_gen.py (Bank: make / public / check). Условия написаны по образцу экзаменационных
(кодификатор ФИПИ), не копии заданий банка. Все нужные константы названы в условии, g = 10 м/с², как в КИМ.
Ответ считается точно (Fraction): число без единиц, не больше двух знаков после запятой — как в бланке.
Номера с графиками, схемами и выбором утверждений здесь не генерируются.
"""
from fractions import Fraction as F

from .inf_gen import _cnt
from .math_gen import Bank, finite, fmt

G = 10


def _f(x):
    return fmt(F(x))


def D(s):
    """«0,5» → Fraction(1, 2): десятичные данные пишем так же, как в условии."""
    return F(str(s).replace(",", "."))


def _gen(*kinds):
    """Номер = несколько видов задач; вид выбирается случайно, неудачные числа (длинная дробь) перебрасываются."""
    def g(r):
        for _ in range(500):
            try:
                out = r.choice(kinds)(r)
            except ValueError:                # в данных вышла бесконечная дробь — берём другие числа
                continue
            if not out:
                continue
            text, ans, expl = out
            ans = F(ans)
            if ans and finite(ans) and (ans * 100).denominator == 1 and abs(ans) < 10 ** 7:
                return {"text": text, "answer": fmt(ans), "explain": expl % _f(ans) if "%s" in expl else expl}
        raise RuntimeError("не нашлись числа")
    return g


