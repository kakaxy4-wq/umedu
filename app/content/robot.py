def _under_wall(a):
    f = _Field()
    for x in range(a):
        f.above(x, 0)
        f.target.add((x, 0))
    return f.done()


def _corner(a, b):
    """Горизонтальная стена, от её правого конца вниз — вертикальная."""
    f = _Field()
    for x in range(a):
        f.above(x, 0)
        f.target.add((x, 0))
    for y in range(b):
        f.right(a - 1, y)
        f.target.add((a - 1, y))
    return f.done()


def _gap(a, g, gw):
    """Горизонтальная стена длиной a с проходом шириной gw, начиная с клетки g."""
    f = _Field()
    for x in range(a):
        if g <= x < g + gw:
            continue
        f.above(x, 0)
        f.target.add((x, 0) if x < g else (x, -1))
    return f.done()


def _step_down(a, b):
    """Вертикальная стена (Робот слева от неё), от её нижнего конца вправо — горизонтальная."""
    f = _Field()
    for y in range(a):
        f.right(0, y)
        f.target.add((0, y))
    f.target.add((0, a))
    for x in range(1, b + 1):
        f.below(x, a - 1)
        f.target.add((x, a))
    return f.done()


def _corridor(a, b):
    """Коридор: стена сверху длиной a и стена снизу длиной b, обе начинаются от Робота."""
    f = _Field()
    for x in range(a):
        f.above(x, 0)
    for x in range(b):
        f.below(x, 0)
    for x in range(min(a, b)):
        f.target.add((x, 0))
    return f.done()


def _around(a):
    """Горизонтальная стена; закрасить клетки и под ней, и над ней."""
    f = _Field()
    for x in range(a):
        f.above(x, 0)
        f.target.add((x, 0))
        f.target.add((x, -1))
    return f.done()


def _vgap(a, g, gw):
    """Вертикальная стена длиной a с проходом шириной gw, начиная с клетки g (Робот слева от верхнего конца)."""
    f = _Field()
    for y in range(a):
        if g <= y < g + gw:
            continue
        f.right(0, y)
        f.target.add((0, y) if y < g else (1, y))
    return f.done()


def _turn(a, b):
    """Коридор шириной в клетку: a клеток вправо, угловая клетка, потом b клеток вниз."""
    f = _Field()
    for x in range(a + 1):
        f.above(x, 0)
    for x in range(a):
        f.below(x, 0)
        f.target.add((x, 0))
    f.target.add((a, 0))
    for y in range(b + 1):
        f.right(a, y)
    for y in range(1, b + 1):
        f.right(a - 1, y)
        f.target.add((a, y))
    return f.done()


