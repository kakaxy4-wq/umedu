class _Field:
    def __init__(self):
        self.walls = []
        self.target = set()
        self.start = (0, 0)

    def above(self, x, y):
        self.walls.append((x, y - 1, "d"))

    def below(self, x, y):
        self.walls.append((x, y, "d"))

    def right(self, x, y):
        self.walls.append((x, y, "r"))

    def done(self):
        cells = [self.start, *self.target]
        for x, y, side in self.walls:
            cells += [(x, y), (x + 1, y) if side == "r" else (x, y + 1)]
        x0 = min(c[0] for c in cells) - MARGIN
        y0 = min(c[1] for c in cells) - MARGIN
        x1 = max(c[0] for c in cells) + MARGIN
        y1 = max(c[1] for c in cells) + MARGIN
        return {"w": x1 - x0 + 1, "h": y1 - y0 + 1,
                "walls": [[x - x0, y - y0, s] for x, y, s in self.walls],
                "start": [self.start[0] - x0, self.start[1] - y0],
                "target": sorted([x - x0, y - y0] for x, y in self.target)}


