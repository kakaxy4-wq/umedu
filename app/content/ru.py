def check_dictation(d, letters, commas):
    """letters — выбранные варианты по порядку пропусков, commas — номера слов, после которых поставлена запятая."""
    letters = letters if isinstance(letters, list) else []
    got = {int(c) for c in (commas if isinstance(commas, list) else []) if str(c).isdigit() and int(c) in d["can"]}
    lres = [{"ok": i < len(letters) and letters[i] == g["answer"], "answer": g["answer"], "rule": g["rule"]}
            for i, g in enumerate(d["letters"])]
    missing = sorted(set(d["need"]) - got)
    extra = sorted(got - set(d["need"]))
    return {"letters": lres, "need": sorted(d["need"]), "missing": missing, "extra": extra,
            "errors": sum(not x["ok"] for x in lres) + len(missing) + len(extra)}
