_LETTER = re.compile(r"\[([^|\]]+)\|([^|\]]+)\|([a-z_]+)\]")


def _parse_dictation(did, title, text):
    words, letters, need, can = [], [], {}, []
    tokens = text.split()
    for i, tok in enumerate(tokens):
        m = re.search(r",\^([a-z_]+)$", tok)
        if m:
            need[i] = m.group(1)
            tok = tok[:m.start()]
        parts, pos = [], 0
        for g in _LETTER.finditer(tok):
            if g.start() > pos:
                parts.append(tok[pos:g.start()])
            parts.append({"g": len(letters)})
            letters.append({"answer": g.group(1), "options": g.group(2).split("/"), "rule": g.group(3)})
            pos = g.end()
        if pos < len(tok):
            parts.append(tok[pos:])
        words.append(parts)
        if i < len(tokens) - 1 and tok[-1] not in ".!?":
            can.append(i)
    plain = []
    for i, parts in enumerate(words):
        w = "".join(p if isinstance(p, str) else letters[p["g"]]["answer"] for p in parts)
        plain.append(w + ("," if i in need else ""))
    return {"id": did, "title": title, "words": words, "letters": letters, "need": need, "can": can,
            "text": " ".join(plain)}


