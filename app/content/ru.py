def check_comma(item, chosen):
    """chosen — номера промежутков (после слова i). Возвращает (верно ли, лишние, пропущенные)."""
    chosen = {int(c) for c in chosen if str(c).isdigit() and 0 <= int(c) < len(item["words"]) - 1}
    right = set(item["gaps"])
    return chosen == right, sorted(chosen - right), sorted(right - chosen)


def check_basis(item, given):
    """given — {"s": [номера слов-подлежащих], "p": [номера слов-сказуемых]}. Возвращает (верно ли, s, p)."""
    n = len(item["words"])

    def nums(key):
        v = given.get(key) if isinstance(given, dict) else None
        return {int(x) for x in (v if isinstance(v, list) else []) if str(x).isdigit() and int(x) < n}
    s, p = nums("s"), nums("p")
    return s == set(item["s"]) and p == set(item["p"]), sorted(s), sorted(p)


def check_spell(item, answer):
    return answer == item["answer"]


def spelled(item):
    """Слово с правильно вставленной буквой — для разбора ошибки."""
    a = item["answer"]
    t = item["text"]
    if t.startswith("(не)"):
        return ("не" + t[4:]) if a == "слитно" else ("не " + t[4:])
    return t.replace("_", "" if a == "—" else a, 1)


