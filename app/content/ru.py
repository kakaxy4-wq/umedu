def _parse_commas(item_id, rule, sentence):
    end = sentence[-1] if sentence[-1] in ".!?" else ""
    body = sentence[:-1] if end else sentence
    raw = body.split()
    words, gaps = [], []
    for i, w in enumerate(raw):
        if w.endswith(","):
            gaps.append(i)
            w = w[:-1]
        words.append(w)
    return {"id": item_id, "rule": rule, "words": words, "end": end, "gaps": sorted(gaps), "text": sentence}


def _parse_basis(item_id, rule, sentence):
    words, subj, pred = [], [], []
    for i, w in enumerate(sentence.split()):
        if w[0] == "*":
            subj.append(i)
        elif w[0] == "=":
            pred.append(i)
        words.append(w.lstrip("*="))
    return {"id": item_id, "rule": rule, "words": words, "s": subj, "p": pred, "text": " ".join(words)}


