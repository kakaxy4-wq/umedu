// Стакан воды, нагреватель и термометр.
(function () {
  LabEngine.scene("heat", function (g, v) {
    var c = v.colors, w = v.w, h = v.h;
    g.fillStyle = c.bg;
    g.fillRect(0, 0, w, h);
    var cx = w * 0.42, top = 36, bot = h - 28, bw = Math.min(150, w * 0.38);
    g.strokeStyle = c.text;
    g.lineWidth = 3;
    g.beginPath();
    g.moveTo(cx - bw / 2, top + 20);
    g.lineTo(cx - bw / 2 + 10, bot);
    g.lineTo(cx + bw / 2 - 10, bot);
    g.lineTo(cx + bw / 2, top + 20);
    g.stroke();
    var temp = v.out.T || 20;
    var level = Math.max(0.25, Math.min(0.85, 0.45 + (v.controls.m || 0.2) * 0.4));
    var yWater = top + 20 + (bot - top - 20) * (1 - level);
    g.fillStyle = c.ultra;
    g.globalAlpha = 0.35;
    g.beginPath();
    g.moveTo(cx - bw / 2 + 6, yWater);
    g.lineTo(cx - bw / 2 + 12, bot - 2);
    g.lineTo(cx + bw / 2 - 12, bot - 2);
    g.lineTo(cx + bw / 2 - 6, yWater);
    g.closePath();
    g.fill();
    g.globalAlpha = 1;
    var heat = Math.min(1, (v.controls.P || 0) / 400);
    g.strokeStyle = c.weak;
    g.globalAlpha = 0.45 + 0.55 * heat;
    g.lineWidth = 2;
    g.beginPath();
    var hy = bot - 16;
    g.moveTo(cx - 30, hy);
    for (var i = 0; i < 8; i++) g.lineTo(cx - 30 + i * 8, hy + (i % 2 ? -8 : 8));
    g.stroke();
    g.globalAlpha = 1;
    var tx = cx + bw / 2 + 28;
    g.strokeStyle = c.text;
    g.lineWidth = 3;
    g.strokeRect(tx, top, 18, bot - top - 10);
    g.beginPath();
    g.arc(tx + 9, bot - 8, 12, 0, 6.3);
    g.stroke();
    var frac = Math.max(0, Math.min(1, (temp - 15) / 80));
    var colH = (bot - top - 24) * frac;
    g.fillStyle = c.weak;
    g.fillRect(tx + 6, bot - 16 - colH, 6, colH);
    g.fillStyle = c.text;
    g.font = "700 18px Golos Text, sans-serif";
    g.textAlign = "left";
    g.fillText((v.shown.T != null ? v.shown.T : temp).toFixed(1).replace(".", ",") + " °C", tx + 28, top + 28);
    g.font = "13px Golos Text, sans-serif";
    g.fillStyle = c.muted;
    g.fillText(Math.round(v.controls.tau) + " с · " + Math.round(v.controls.P) + " Вт", cx - bw / 2, top + 8);
  });
})();
